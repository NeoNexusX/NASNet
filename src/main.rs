//! NASNet Rust 学习与项目实现：12 课课程安排。
//!
//! 进度：第 1 课已完成；第 2 课进行中（地址校验完成，协议校验待完成）。
//! 每课整合两个原学习单元，增加完整功能、动手实现和验收范围；可以分多轮完成。
//! 本课程表是长期项目安排，检查完成练习时保留；只清理对应实现中的临时学习提示。
//! 详细大纲：docs/Course-Syllabus.md。
//!
//! 01. 设备模型、所有权、查询与排序
//!     Rust：struct、impl、String、Vec、移动、共享/可变借用、Option、迭代器与闭包。
//!     项目：完成设备和地址的创建、添加、计数、改名、查询与稳定优先级排序。
//!     动手：亲写模型方法、借用查找和引用列表排序；解释数据归属及可变性。
//!     完成：空列表和不存在的 ID 可处理；同优先级稳定；原保存顺序不变。
//!
//! 02. 错误处理与独立 NFS/SMB 配置
//!     Rust：enum、Result、?、单元类型、带数据枚举、借用匹配、`Option<String>` 与切片。
//!     项目：完成 Host/地址校验、重复 ID 检查、独立协议配置、协议分派和连接保存。
//!     动手：亲写两种协议的配置校验与枚举分派；按成功后才修改列表的顺序处理。
//!     完成：错误原因明确；失败不改列表；NFS/SMB 身份独立，连接列表只读借用。
//!
//! 03. 模型封装、生命周期与配置序列化
//!     Rust：模块可见性、私有字段、构造与修改方法、借用返回值、生命周期基础、派生 trait 与 Serde。
//!     项目：统一设备/地址/连接的合法创建和更新入口，设计保存数据并实现序列化与恢复。
//!     动手：亲写构造/更新/删除接口、数据转换与反序列化后的校验；按需练习基础泛型。
//!     完成：公开接口不能绕过校验；还原配置仍检查规则；ID、关联和顺序保持一致。
//!
//! 04. SQLite、系统凭据与配置闭环
//!     Rust：存储 trait、外部依赖、错误转换、SQL 参数与事务、文件路径及外部 API 封装。
//!     项目：保存和加载设备、地址、协议配置，对接系统凭据存储，形成重启可恢复的配置流程。
//!     动手：亲写存储接口的关键实现、事务保存/加载和凭据引用的创建/读取/清理流程。
//!     完成：配置跨重启恢复；失败不留下半份配置；密码不进入普通配置和日志。
//!
//! 05. C FFI、指针与资源安全封装
//!     Rust：C ABI、`extern "C"`、裸指针、unsafe、CString/CStr、NonNull、Drop 与 RAII。
//!     项目：先完成小型 C 调用，再将创建/使用/关闭句柄封装成安全的 Rust 接口。
//!     动手：亲写字符串转换、返回值检查、句柄构造和 Drop；说明每块内存的归属与有效期。
//!     完成：错误和提前返回路径正确释放；无双重释放或悬空访问；unsafe 边界清晰。
//!
//! 06. 真实 NFS 与 SMB 协议接入
//!     Rust：原生依赖构建、绑定、协议适配、业务错误转换、凭据获取与句柄所有权。
//!     项目：固定并构建 libnfs/libsmb2，分别连接真实导出和共享，读取目录并释放资源。
//!     动手：亲写关键连接调用、配置到后端的转换、目录结果转换与失败清理。
//!     完成：两种协议分别在真实 NAS 验证；配置和身份不混用；错误保留真实原因。
//!
//! 07. 统一远程能力与异步调用
//!     Rust：业务 trait、统一数据结构、能力表达、async/await、线程、通道及 Send/Sync。
//!     项目：统一目录/文件/权限元数据接口，按能力提供权限操作，并建立异步调用与 C 上下文调度边界。
//!     动手：亲写公共操作接口、协议适配、异步请求转交和结果返回；明确 C 上下文的拥有者。
//!     完成：调用界面无需硬编码协议差异；不支持的能力明确报告；C 上下文不被无依据地并发共享。
//!
//! 08. 会话管理、取消与地址故障切换
//!     Rust：状态枚举、消息传递、按需使用 Arc、取消、超时、重试与错误传播。
//!     项目：管理连接生命周期，支持取消与安全关闭，按稳定优先级选择地址并处理失效重连。
//!     动手：亲写会话状态流转、取消清理、地址尝试和错误分类后的重试决策。
//!     完成：网络失败可换地址；认证/权限失败默认停止；健康会话保持地址；取消后资源正确释放。
//!
//! 09. 终端应用、独立后台与本地 IPC
//!     Rust：参数输入、业务编排、进程边界、消息序列化、请求/响应与事件。
//!     项目：形成可用的终端版，再把连接和远程操作放入独立用户后台，通过本地 IPC 调用。
//!     动手：亲写命令编排、消息处理、请求关联、错误响应和后台退出流程。
//!     完成：从保存配置访问真实 NAS；终端能浏览/读取/取消；客户端退出后后台按设计继续运行。
//!
//! 10. Tauri/Vue 桌面与配置管理
//!     Rust：Rust 命令接口、前后端数据类型、IPC 错误映射与表单校验对接。
//!     项目：建立桌面骨架，管理设备、地址顺序、独立协议配置及凭据引用。
//!     动手：重点亲写 Rust 命令与后台业务接线、输入转换和错误映射；前端工程由助手协助搭建。
//!     完成：界面能完整保存和恢复配置；表单错误清楚；后台是业务数据的统一入口。
//!
//! 11. 远程浏览界面与系统挂载
//!     Rust：后台事件、状态与取消、能力数据、平台 trait、cfg、系统 API/进程封装。
//!     项目：展示远程目录/文件/权限及连接状态，接入当前系统支持的挂载和卸载。
//!     动手：亲写事件/操作状态处理、挂载适配接口和能力检查；协助验证界面与后台联动。
//!     完成：关闭窗口后后台仍工作；浏览与挂载分别管理；占用时明确报告，不自动强制卸载。
//!
//! 12. 自动恢复、跨平台打包与交付
//!     Rust：后台生命周期、状态持久化、幂等恢复、条件编译、固定工具链与发布构建。
//!     项目：用户登录后自启、按配置恢复连接/挂载，整理原生依赖并打包目标平台版本。
//!     动手：亲写启动恢复和幂等判断，处理重复启动/占用/失败；参与平台构建与实际验证。
//!     完成：不重复挂载；失败可解释；在可用目标系统验证安装/启动/退出，记录平台能力限制。
//!
//! 运行入口仍采用原有演示编号，与合并后的课号分开：
//!   lesson01、lesson02 → 第 1 课的模型、查询与排序小节。
